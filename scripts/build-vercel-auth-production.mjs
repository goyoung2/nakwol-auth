import { build } from 'esbuild';
import { spawnSync } from 'node:child_process';
import { mkdir,copyFile,readFile,writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
const root=fileURLToPath(new URL('..',import.meta.url)),out=resolve(root,'deploy/vercel-auth-production');
const packed=spawnSync(process.execPath,['scripts/build-connect-cli-package.mjs'],{cwd:root,stdio:'inherit'});if(packed.status!==0)throw new Error('CONNECT_PACKAGE_BUILD_FAILED');
await mkdir(resolve(out,'api'),{recursive:true});await mkdir(resolve(out,'runtime'),{recursive:true});
await build({absWorkingDir:root,entryPoints:['adapters/vercel/entry.ts'],outfile:resolve(out,'runtime/auth-runtime.mjs'),bundle:true,platform:'node',target:'node22',format:'esm',loader:{'.txt':'text'},legalComments:'none'});
await build({absWorkingDir:root,entryPoints:['adapters/vercel/bridge-worker.ts'],outfile:resolve(out,'bridge-worker.mjs'),bundle:true,platform:'browser',target:'es2022',format:'esm'});
for(const name of ['api/index.mjs','build.mjs','vercel.json','.vercelignore'])await copyFile(resolve(root,'deploy/vercel-auth-test',name),resolve(out,name));
const canonical=JSON.parse(await readFile(resolve(root,'deploy/vercel-auth-test/package.json'),'utf8'));
const lock=JSON.parse(await readFile(resolve(root,'deploy/vercel-auth-test/package-lock.json'),'utf8'));
canonical.name='nakwol-auth-vercel-production';delete canonical.devDependencies;canonical.scripts={build:'node build.mjs'};
await writeFile(resolve(out,'package.json'),JSON.stringify(canonical,null,2));
lock.name=canonical.name;lock.packages[''].name=canonical.name;delete lock.packages[''].devDependencies;
for(const [path,value]of Object.entries(lock.packages))if(path&&value.dev===true)delete lock.packages[path];
await writeFile(resolve(out,'package-lock.json'),JSON.stringify(lock,null,2));
console.log('VERCEL_PRODUCTION_ARTIFACT_PREPARED_NOT_DEPLOYED');
